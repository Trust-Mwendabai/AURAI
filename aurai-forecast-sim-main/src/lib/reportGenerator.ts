import jsPDF from 'jspdf';
import html2canvas from 'html2canvas';

export interface ReportData {
  forecastName: string;
  targetColumn: string;
  algorithm: string;
  horizon: number;
  period: string;
  accuracy: number | null;
  createdAt: string;
  datasetName: string;
  chartElement: HTMLElement | null;
  advice: string;
  metrics: {
    swing: number | null;
    volatility: number | null;
    uncertainty: number | null;
    bandWidth: number | null;
  };
  forecastData: Array<{
    label: string;
    value: number;
    low: number;
    high: number;
  }>;
  historyData?: Array<{ label: string; value: number }>;
  anomalies?: Array<{
    date: string;
    actual_value: number;
    forecasted_value: number;
    anomaly_type: string;
    deviation_sigma: number;
  }>;
  scenarios?: Array<{
    name: string;
    metrics: { adjustedTotal: number; percentChange: number } | null;
  }>;
}

const PAGE = { width: 210, height: 297, margin: 16 };
const CONTENT_WIDTH = PAGE.width - 2 * PAGE.margin;
const BRAND = { r: 124, g: 92, b: 255 }; // matches --gradient-primary's violet

/** Draws the same footer (brand mark, dataset, page number) on every page,
 * called once at the very end once the final page count is known — jsPDF
 * has no live page-count while content is still being written. */
function paintFooters(pdf: jsPDF, datasetName: string) {
  const totalPages = pdf.internal.pages.length - 1;
  for (let i = 1; i <= totalPages; i++) {
    pdf.setPage(i);
    const y = PAGE.height - 10;
    pdf.setDrawColor(230, 230, 230);
    pdf.line(PAGE.margin, y - 4, PAGE.width - PAGE.margin, y - 4);
    pdf.setFontSize(8);
    pdf.setTextColor(150, 150, 150);
    pdf.setFont('Helvetica', 'normal');
    pdf.text(`Dataset: ${datasetName} · Generated by Aurai`, PAGE.margin, y);
    pdf.text(`Page ${i} of ${totalPages}`, PAGE.width - PAGE.margin, y, { align: 'right' });
  }
}

/** Section heading with a colored accent bar — used to give each part of
 * the report a clear visual break instead of relying on font size alone. */
function sectionHeading(pdf: jsPDF, title: string, y: number): number {
  pdf.setFillColor(BRAND.r, BRAND.g, BRAND.b);
  pdf.rect(PAGE.margin, y - 4, 3, 6, 'F');
  pdf.setFontSize(13);
  pdf.setTextColor(30, 30, 30);
  pdf.setFont('Helvetica', 'bold');
  pdf.text(title, PAGE.margin + 6, y);
  return y + 9;
}

function ensureSpace(pdf: jsPDF, y: number, needed: number): number {
  if (y + needed > PAGE.height - PAGE.margin - 14) {
    pdf.addPage();
    return PAGE.margin;
  }
  return y;
}

/** A minimal table renderer (no autotable dependency): draws a header row,
 * then body rows, paginating automatically when a row would run past the
 * footer zone. Column widths are proportions of CONTENT_WIDTH. */
function drawTable(
  pdf: jsPDF,
  y: number,
  columns: { label: string; width: number; align?: 'left' | 'right' }[],
  rows: string[][],
  options: { zebra?: boolean } = {},
): number {
  const rowHeight = 6.2;
  const headerHeight = 7;

  const drawHeader = (yy: number) => {
    pdf.setFillColor(245, 244, 250);
    pdf.rect(PAGE.margin, yy - 5, CONTENT_WIDTH, headerHeight, 'F');
    pdf.setFontSize(8.5);
    pdf.setFont('Helvetica', 'bold');
    pdf.setTextColor(90, 80, 130);
    let x = PAGE.margin + 2;
    for (const col of columns) {
      pdf.text(col.label, col.align === 'right' ? x + col.width - 4 : x, yy, { align: col.align === 'right' ? 'right' : 'left' });
      x += col.width;
    }
    return yy + headerHeight;
  };

  y = ensureSpace(pdf, y, headerHeight + rowHeight);
  y = drawHeader(y);

  pdf.setFont('Helvetica', 'normal');
  pdf.setFontSize(8.5);

  rows.forEach((row, i) => {
    if (y + rowHeight > PAGE.height - PAGE.margin - 14) {
      pdf.addPage();
      y = PAGE.margin;
      y = drawHeader(y);
    }
    if (options.zebra && i % 2 === 1) {
      pdf.setFillColor(250, 250, 252);
      pdf.rect(PAGE.margin, y - 4.5, CONTENT_WIDTH, rowHeight, 'F');
    }
    pdf.setTextColor(60, 60, 60);
    let x = PAGE.margin + 2;
    row.forEach((cell, ci) => {
      const col = columns[ci];
      pdf.text(cell, col.align === 'right' ? x + col.width - 4 : x, y, { align: col.align === 'right' ? 'right' : 'left' });
      x += col.width;
    });
    y += rowHeight;
  });

  return y + 4;
}

function fmt(n: number | null | undefined): string {
  if (n === null || n === undefined || isNaN(n)) return '—';
  return n.toLocaleString(undefined, { maximumFractionDigits: 1 });
}

export async function generateExecutiveReport(data: ReportData): Promise<void> {
  const pdf = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  pdf.setFont('Helvetica', 'normal');
  let y = PAGE.margin;

  // ---------------------------------------------------------------------
  // COVER
  // ---------------------------------------------------------------------
  pdf.setFillColor(BRAND.r, BRAND.g, BRAND.b);
  pdf.rect(0, 0, PAGE.width, 55, 'F');
  pdf.setTextColor(255, 255, 255);
  pdf.setFontSize(11);
  pdf.setFont('Helvetica', 'bold');
  pdf.text('AURAI', PAGE.margin, 18);
  pdf.setFontSize(9);
  pdf.setFont('Helvetica', 'normal');
  pdf.text('Forecast Intelligence Report', PAGE.margin, 25);

  pdf.setFontSize(24);
  pdf.setFont('Helvetica', 'bold');
  pdf.text(data.forecastName, PAGE.margin, 42, { maxWidth: CONTENT_WIDTH });

  y = 68;
  pdf.setTextColor(30, 30, 30);
  pdf.setFontSize(10);
  pdf.setFont('Helvetica', 'normal');
  const coverLines: [string, string][] = [
    ['Dataset', data.datasetName || 'Unknown dataset'],
    ['Target column', data.targetColumn],
    ['Model', `${data.algorithm}${data.accuracy !== null ? ` · ${data.accuracy}% accuracy` : ''}`],
    ['Forecast horizon', `${data.horizon} ${data.period}`],
    ['Generated', new Date(data.createdAt).toLocaleString()],
  ];
  coverLines.forEach(([label, value]) => {
    pdf.setFont('Helvetica', 'bold');
    pdf.setTextColor(100, 100, 100);
    pdf.text(label.toUpperCase(), PAGE.margin, y);
    pdf.setFont('Helvetica', 'normal');
    pdf.setTextColor(30, 30, 30);
    pdf.text(value, PAGE.margin + 45, y);
    y += 7;
  });

  y += 6;
  pdf.setDrawColor(230, 230, 230);
  pdf.line(PAGE.margin, y, PAGE.width - PAGE.margin, y);
  y += 10;

  // ---------------------------------------------------------------------
  // KEY METRICS — computed from the full forecast, not just what's charted
  // ---------------------------------------------------------------------
  const values = data.forecastData.map((f) => f.value);
  const lows = data.forecastData.map((f) => f.low);
  const highs = data.forecastData.map((f) => f.high);
  const total = values.reduce((a, b) => a + b, 0);
  const totalLow = lows.reduce((a, b) => a + b, 0);
  const totalHigh = highs.reduce((a, b) => a + b, 0);
  const average = values.length ? total / values.length : 0;
  const peak = values.length ? Math.max(...values) : 0;
  const trough = values.length ? Math.min(...values) : 0;
  const peakPoint = data.forecastData.find((f) => f.value === peak);
  const troughPoint = data.forecastData.find((f) => f.value === trough);
  // First-to-last, not period-to-period — the headline direction over the
  // whole horizon, which period-over-period alone (in the detailed table
  // below) doesn't show at a glance.
  const overallChangePct = values.length > 1 && values[0] !== 0
    ? ((values[values.length - 1] - values[0]) / Math.abs(values[0])) * 100
    : null;

  // -----------------------------------------------------------------
  // AT A GLANCE — scan-in-five-seconds bullets before any table or chart
  // -----------------------------------------------------------------
  y = sectionHeading(pdf, 'At a Glance', y);
  pdf.setFontSize(9.5);
  pdf.setFont('Helvetica', 'normal');
  const glanceBullets = [
    `${data.targetColumn} is projected to ${overallChangePct === null ? 'hold roughly flat' : overallChangePct >= 0 ? `rise ${overallChangePct.toFixed(1)}%` : `fall ${Math.abs(overallChangePct).toFixed(1)}%`} across the ${data.horizon}-${data.period.toLowerCase()} horizon.`,
    `Total across all periods: ${fmt(total)}, ranging from ${fmt(totalLow)} (worst case) to ${fmt(totalHigh)} (best case).`,
    `Peak of ${fmt(peak)} expected in ${peakPoint?.label ?? '—'}; lowest point ${fmt(trough)} in ${troughPoint?.label ?? '—'}.`,
    data.accuracy !== null
      ? `The model matched ${data.accuracy}% of held-back historical data — ${data.accuracy >= 90 ? 'a strong basis for planning' : data.accuracy >= 75 ? 'reasonably reliable, with some caution' : 'treat as directional rather than precise'}.`
      : `Accuracy could not be scored — there wasn't enough history to hold data back for testing.`,
  ];
  for (const bullet of glanceBullets) {
    y = ensureSpace(pdf, y, 6);
    pdf.setTextColor(BRAND.r, BRAND.g, BRAND.b);
    pdf.text('•', PAGE.margin, y);
    pdf.setTextColor(50, 50, 50);
    const lines = pdf.splitTextToSize(bullet, CONTENT_WIDTH - 5);
    pdf.text(lines, PAGE.margin + 5, y);
    y += lines.length * 5 + 1.5;
  }
  y += 6;

  // -----------------------------------------------------------------
  // RISK SCENARIOS — best/base/worst case side by side
  // -----------------------------------------------------------------
  y = ensureSpace(pdf, y, 26);
  y = sectionHeading(pdf, 'Risk Scenarios (Total Across Horizon)', y);
  const scenarioCols = [
    { label: 'WORST CASE', value: totalLow, color: [200, 60, 60] },
    { label: 'BASE CASE', value: total, color: [90, 80, 130] },
    { label: 'BEST CASE', value: totalHigh, color: [40, 150, 100] },
  ];
  const scWidth = CONTENT_WIDTH / 3;
  scenarioCols.forEach((sc, i) => {
    const x = PAGE.margin + i * scWidth;
    pdf.setFillColor(248, 247, 251);
    pdf.rect(x, y - 5, scWidth - 3, 18, 'F');
    pdf.setFontSize(7.5);
    pdf.setFont('Helvetica', 'bold');
    pdf.setTextColor(120, 120, 120);
    pdf.text(sc.label, x + 3, y);
    pdf.setFontSize(13);
    pdf.setTextColor(sc.color[0], sc.color[1], sc.color[2]);
    pdf.text(fmt(sc.value), x + 3, y + 8);
  });
  y += 20;

  y = sectionHeading(pdf, 'Key Metrics', y);

  const metricsData: [string, string][] = [
    ['Total forecasted', fmt(total)],
    ['Average per period', fmt(average)],
    ['Peak', `${fmt(peak)}${peakPoint ? ` (${peakPoint.label})` : ''}`],
    ['Trough', `${fmt(trough)}${troughPoint ? ` (${troughPoint.label})` : ''}`],
    ['Confidence band', data.metrics.bandWidth !== null ? `±${data.metrics.bandWidth.toFixed(1)}%` : 'N/A'],
    ['Volatility', data.metrics.volatility !== null ? `${data.metrics.volatility.toFixed(1)}%` : 'N/A'],
    ['Accuracy (on held-out history)', data.accuracy !== null ? `${data.accuracy}%` : 'Not scored'],
    ['Algorithm', data.algorithm],
  ];

  const colWidth = CONTENT_WIDTH / 2;
  pdf.setFontSize(9.5);
  metricsData.forEach((row, i) => {
    const col = i % 2;
    const rowY = y + Math.floor(i / 2) * 7;
    const x = PAGE.margin + col * colWidth;
    pdf.setFont('Helvetica', 'bold');
    pdf.setTextColor(90, 80, 130);
    pdf.text(row[0], x, rowY);
    pdf.setFont('Helvetica', 'normal');
    pdf.setTextColor(30, 30, 30);
    pdf.text(row[1], x + colWidth - 4, rowY, { align: 'right' });
  });
  y += Math.ceil(metricsData.length / 2) * 7 + 10;

  // ---------------------------------------------------------------------
  // CHART
  // ---------------------------------------------------------------------
  if (data.chartElement) {
    try {
      y = ensureSpace(pdf, y, 20);
      y = sectionHeading(pdf, 'Forecast Chart', y);

      const resolvedBg = getComputedStyle(document.body).backgroundColor || '#ffffff';
      const canvas = await html2canvas(data.chartElement, { backgroundColor: resolvedBg, scale: 2 });
      const imgData = canvas.toDataURL('image/png');
      const chartWidth = CONTENT_WIDTH;
      const chartHeight = (canvas.height / canvas.width) * chartWidth;

      y = ensureSpace(pdf, y, chartHeight);
      pdf.addImage(imgData, 'PNG', PAGE.margin, y, chartWidth, chartHeight);
      y += chartHeight + 10;
    } catch (e) {
      console.error('Failed to embed chart:', e);
      pdf.setFontSize(9);
      pdf.setTextColor(180, 0, 0);
      pdf.text('Chart could not be embedded.', PAGE.margin, y);
      y += 8;
    }
  }

  // ---------------------------------------------------------------------
  // AI / ANALYST COMMENTARY
  // ---------------------------------------------------------------------
  if (data.advice) {
    y = ensureSpace(pdf, y, 20);
    y = sectionHeading(pdf, 'Analyst Commentary', y);

    pdf.setFontSize(9.5);
    pdf.setTextColor(60, 60, 60);
    pdf.setFont('Helvetica', 'normal');

    // Strip simple markdown bold markers (**text**) rather than render them
    // literally — jsPDF has no rich-text runs, so bolding a sub-span would
    // need per-segment font switches; plain text through splitTextToSize is
    // the accurate trade-off here.
    const plainAdvice = data.advice.replace(/\*\*(.+?)\*\*/g, '$1');
    const lines = pdf.splitTextToSize(plainAdvice, CONTENT_WIDTH);
    for (const line of lines) {
      y = ensureSpace(pdf, y, 5);
      pdf.text(line, PAGE.margin, y);
      y += 5;
    }
    y += 6;
  }

  // ---------------------------------------------------------------------
  // RECENT HISTORY (if provided)
  // ---------------------------------------------------------------------
  if (data.historyData && data.historyData.length > 0) {
    y = ensureSpace(pdf, y, 20);
    y = sectionHeading(pdf, 'Recent Recorded History', y);
    pdf.setFontSize(8.5);
    pdf.setTextColor(100, 100, 100);
    pdf.setFont('Helvetica', 'normal');
    pdf.text('The actual recorded values the forecast below continues from.', PAGE.margin, y);
    y += 6;

    y = drawTable(
      pdf, y,
      [
        { label: 'PERIOD', width: CONTENT_WIDTH * 0.5 },
        { label: 'RECORDED VALUE', width: CONTENT_WIDTH * 0.5, align: 'right' },
      ],
      data.historyData.slice(-24).map((h) => [h.label, fmt(h.value)]),
      { zebra: true },
    );
  }

  // ---------------------------------------------------------------------
  // FULL FORECAST DATA TABLE — every period, not just the chart
  // ---------------------------------------------------------------------
  y = ensureSpace(pdf, y, 20);
  y = sectionHeading(pdf, 'Detailed Forecast — All Periods', y);
  pdf.setFontSize(8.5);
  pdf.setTextColor(100, 100, 100);
  pdf.setFont('Helvetica', 'normal');
  pdf.text('The estimate is the model\'s single best guess; the actual result is expected to fall between the bounds most of the time.', PAGE.margin, y);
  y += 6;

  y = drawTable(
    pdf, y,
    [
      { label: 'PERIOD', width: CONTENT_WIDTH * 0.22 },
      { label: 'LOWER BOUND', width: CONTENT_WIDTH * 0.2, align: 'right' },
      { label: 'ESTIMATE', width: CONTENT_WIDTH * 0.2, align: 'right' },
      { label: 'UPPER BOUND', width: CONTENT_WIDTH * 0.2, align: 'right' },
      { label: 'VS PRIOR PERIOD', width: CONTENT_WIDTH * 0.18, align: 'right' },
    ],
    data.forecastData.map((f, i) => {
      const prev = i > 0 ? data.forecastData[i - 1].value : null;
      const change = prev !== null && prev !== 0 ? ((f.value - prev) / Math.abs(prev)) * 100 : null;
      const changeStr = change === null ? '—' : `${change >= 0 ? '+' : ''}${change.toFixed(1)}%`;
      return [f.label, fmt(f.low), fmt(f.value), fmt(f.high), changeStr];
    }),
    { zebra: true },
  );

  // ---------------------------------------------------------------------
  // ANOMALIES — where past actuals broke out of this forecast's own range
  // ---------------------------------------------------------------------
  if (data.anomalies && data.anomalies.length > 0) {
    y = ensureSpace(pdf, y, 20);
    y = sectionHeading(pdf, `Anomalies (${data.anomalies.length})`, y);
    pdf.setFontSize(8.5);
    pdf.setTextColor(100, 100, 100);
    pdf.setFont('Helvetica', 'normal');
    pdf.text('Periods where the recorded actual fell outside this forecast\'s own confidence range.', PAGE.margin, y);
    y += 6;

    y = drawTable(
      pdf, y,
      [
        { label: 'DATE', width: CONTENT_WIDTH * 0.22 },
        { label: 'ACTUAL', width: CONTENT_WIDTH * 0.2, align: 'right' },
        { label: 'FORECASTED', width: CONTENT_WIDTH * 0.22, align: 'right' },
        { label: 'DEVIATION', width: CONTENT_WIDTH * 0.18, align: 'right' },
        { label: 'DIRECTION', width: CONTENT_WIDTH * 0.18, align: 'right' },
      ],
      data.anomalies.map((a) => [
        a.date,
        fmt(a.actual_value),
        fmt(a.forecasted_value),
        `${a.deviation_sigma.toFixed(1)}σ`,
        a.anomaly_type === 'above_upper' ? 'Above range' : 'Below range',
      ]),
      { zebra: true },
    );
  }

  // ---------------------------------------------------------------------
  // WHAT-IF SCENARIOS — saved scenarios for this forecast, if any
  // ---------------------------------------------------------------------
  if (data.scenarios && data.scenarios.length > 0) {
    y = ensureSpace(pdf, y, 20);
    y = sectionHeading(pdf, 'What-If Scenarios', y);
    pdf.setFontSize(8.5);
    pdf.setTextColor(100, 100, 100);
    pdf.setFont('Helvetica', 'normal');
    pdf.text('Saved alternative scenarios compared against this forecast\'s base case.', PAGE.margin, y);
    y += 6;

    y = drawTable(
      pdf, y,
      [
        { label: 'SCENARIO', width: CONTENT_WIDTH * 0.4 },
        { label: 'TOTAL', width: CONTENT_WIDTH * 0.3, align: 'right' },
        { label: 'VS BASE CASE', width: CONTENT_WIDTH * 0.3, align: 'right' },
      ],
      [
        ['Base case (this forecast)', fmt(total), '—'],
        ...data.scenarios.map((s) => [
          s.name,
          s.metrics ? fmt(s.metrics.adjustedTotal) : '—',
          s.metrics ? `${s.metrics.percentChange >= 0 ? '+' : ''}${s.metrics.percentChange.toFixed(1)}%` : '—',
        ]),
      ],
      { zebra: true },
    );
  }

  // ---------------------------------------------------------------------
  // METHODOLOGY — how to read this report
  // ---------------------------------------------------------------------
  y = ensureSpace(pdf, y, 30);
  y = sectionHeading(pdf, 'Methodology & How to Read This Report', y);
  pdf.setFontSize(9);
  pdf.setTextColor(60, 60, 60);
  pdf.setFont('Helvetica', 'normal');

  const methodology = [
    `This forecast was produced by ${data.algorithm}, fit on the dataset's recorded history for "${data.targetColumn}".`,
    `Accuracy (${data.accuracy !== null ? data.accuracy + '%' : 'not available'}) measures how closely the model's predictions matched real values it held back during training, not how the future will actually turn out.`,
    'The lower and upper bounds form a confidence interval: the model expects the true value to land inside that range most of the time, and a wider band further into the future reflects growing uncertainty, not a weaker model.',
    'This report is a decision aid, not a guarantee. Treat it alongside domain knowledge of your business, especially around known future events the model could not have seen in historical data (promotions, new products, market shifts).',
  ];
  for (const para of methodology) {
    const lines = pdf.splitTextToSize(para, CONTENT_WIDTH);
    for (const line of lines) {
      y = ensureSpace(pdf, y, 5);
      pdf.text(line, PAGE.margin, y);
      y += 5;
    }
    y += 3;
  }

  paintFooters(pdf, data.datasetName || 'Unknown dataset');

  const filename = `${data.forecastName.replace(/[^a-z0-9]/gi, '-').toLowerCase()}-report.pdf`;
  pdf.save(filename);
}

export async function generateReportFromPrediction(
  prediction: any,
  chartElement: HTMLElement | null,
  insights: any,
  extras?: { anomalies?: any[]; scenarios?: any[] },
): Promise<void> {
  const forecastData = prediction.forecast || [];
  const metrics = {
    swing: insights?.metrics?.swing || null,
    volatility: insights?.metrics?.volatility || null,
    uncertainty: insights?.metrics?.uncertainty || null,
    bandWidth: calculateBandWidth(forecastData),
  };

  await generateExecutiveReport({
    forecastName: prediction.name,
    targetColumn: prediction.target,
    algorithm: prediction.algorithm || 'Prophet',
    horizon: prediction.horizon,
    period: prediction.period,
    accuracy: prediction.accuracy,
    createdAt: prediction.createdAt,
    datasetName: prediction.datasetName || 'Unknown Dataset',
    chartElement,
    advice: insights?.advice || '',
    metrics,
    forecastData,
    historyData: prediction.history || insights?.history || undefined,
    anomalies: extras?.anomalies,
    scenarios: extras?.scenarios,
  });
}

function calculateBandWidth(forecastData: any[]): number | null {
  if (!forecastData?.length) return null;
  const widths = forecastData
    .filter((p: any) => p.high != null && p.low != null && Number(p.value) !== 0)
    .map((p: any) => ((Number(p.high) - Number(p.low)) / Math.abs(Number(p.value))) * 100);
  if (!widths.length) return null;
  return widths.reduce((a: number, b: number) => a + b, 0) / widths.length;
}
