// @ts-nocheck
import { useEffect, useRef, useState } from "react";
import { FiPlus, FiTrash2, FiDownload, FiRefreshCw, FiSearch, FiFilter, FiX, FiCheck, FiFileText } from "react-icons/fi";
import {
  ComposedChart, Line, CartesianGrid, XAxis, YAxis, Tooltip, ResponsiveContainer, ReferenceLine,
} from "recharts";
import { GlassCard } from "@/components/GlassCard";
import { listPredictions, listAnomalies, listScenarios } from "@/lib/db";
import { useToast } from "@/contexts/ToastContext";
import { exportForecastAsCSV } from "@/lib/export";
import { api } from "@/lib/apiClient";
import { generateExecutiveReport } from "@/lib/reportGenerator";
import { SkeletonCardGrid } from "@/components/Skeleton";

export default function ReportsPage() {
  const [reports, setReports] = useState<any[]>([]);
  const [predictions, setPredictions] = useState<any[]>([]);
  const [search, setSearch] = useState("");
  const [filter, setFilter] = useState("all");
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState<string | null>(null);
  const [previewId, setPreviewId] = useState<string | null>(null);
  const [pdfGenerating, setPdfGenerating] = useState<string | null>(null);
  const [pdfChartJob, setPdfChartJob] = useState<any>(null); // { report, prediction } while the off-screen chart renders
  const pdfChartRef = useRef<HTMLDivElement>(null);
  const { success, info } = useToast();

  useEffect(() => {
    loadReports();
    loadPredictions();
  }, []);

  const loadReports = async () => {
    try {
      const data = await api.get('/saved-reports');
      // Filter for auto-generated forecast reports
      const autoReports = data.filter((r: any) => {
        const config = typeof r.config === 'string' ? JSON.parse(r.config) : r.config;
        return config?.autoGenerated === true;
      });
      setReports(autoReports);
    } catch (e) {
      info('Could not load reports', String(e));
    } finally {
      setLoading(false);
    }
  };

  const loadPredictions = async () => {
    try {
      const data = await listPredictions();
      setPredictions(data);
    } catch (e) {
      info('Could not load forecasts', String(e));
    }
  };

  const generateReport = async (predictionId: string) => {
    setGenerating(predictionId);
    try {
      await api.post('/auto-reports/generate', { prediction_id: predictionId });
      success('Report Generated', 'Auto-generated report created successfully');
      loadReports();
    } catch (e) {
      info('Error generating report', String(e));
    } finally {
      setGenerating(null);
    }
  };

  const deleteReport = async (reportId: string) => {
    try {
      await api.del(`/saved-reports/${reportId}`);
      success('Report Deleted', '');
      loadReports();
    } catch (e) {
      info('Failed to delete report', String(e));
    }
  };

  const filteredPredictions = predictions.filter((p) => {
    const matchesSearch = p.name.toLowerCase().includes(search.toLowerCase());
    const hasReport = reports.some((r: any) => {
      const config = typeof r.config === 'string' ? JSON.parse(r.config) : r.config;
      return config?.predictionIds?.includes(p.id);
    });

    if (filter === 'with-reports') return matchesSearch && hasReport;
    if (filter === 'without-reports') return matchesSearch && !hasReport;
    return matchesSearch;
  });

  const downloadReport = (report: any, format: 'json') => {
    const filename = `${report.name.replace(/[^a-z0-9]/gi, '-').toLowerCase()}.${format}`;
    const content = JSON.stringify(report, null, 2);
    const blob = new Blob([content], { type: 'application/json' });
    downloadBlob(blob, filename);
  };

  const downloadBlob = (blob: Blob, filename: string) => {
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const downloadReportCSV = async (report: any) => {
    const config = typeof report.config === 'string' ? JSON.parse(report.config) : report.config;
    const predId = config?.predictionIds?.[0];
    if (!predId) {
      info('No forecast linked to this report', '');
      return;
    }
    try {
      await exportForecastAsCSV(predId, report.name);
    } catch (e) {
      info('CSV export failed', String(e));
    }
  };

  // PDF export needs a live chart element to snapshot (jsPDF embeds an image,
  // not the SVG itself), but the Reports page only shows text summaries — so
  // this renders the forecast into a hidden off-screen chart first, waits a
  // tick for Recharts to paint it, then hands that element to the same PDF
  // builder the Predictions/Insights pages use, and tears the chart down.
  const downloadReportPDF = async (report: any) => {
    const config = typeof report.config === 'string' ? JSON.parse(report.config) : report.config;
    const predId = config?.predictionIds?.[0];
    const prediction = predictions.find((p: any) => p.id === predId);

    if (!prediction) {
      info('No forecast linked to this report', 'Cannot build a PDF without the underlying forecast.');
      return;
    }

    setPdfGenerating(report.id);
    // Best-effort — a report with no recorded anomalies or saved scenarios
    // yet is still a complete report, just without those optional sections.
    const [anomalies, scenarios] = await Promise.all([
      listAnomalies(predId).catch(() => []),
      listScenarios(predId).catch(() => []),
    ]);
    setPdfChartJob({ report, prediction, anomalies, scenarios });
  };

  useEffect(() => {
    if (!pdfChartJob) return;

    // Two frames: one for React to mount the hidden chart, one for Recharts'
    // own layout pass (it measures its container before drawing lines).
    const raf1 = requestAnimationFrame(() => {
      const raf2 = requestAnimationFrame(async () => {
        try {
          await generateExecutiveReport({
            forecastName: pdfChartJob.report.name,
            targetColumn: pdfChartJob.prediction.target,
            algorithm: pdfChartJob.prediction.algorithm || 'Prophet',
            horizon: pdfChartJob.prediction.horizon,
            period: pdfChartJob.prediction.period,
            accuracy: pdfChartJob.prediction.accuracy,
            createdAt: pdfChartJob.report.created_at,
            datasetName: pdfChartJob.prediction.datasetName || 'Dataset',
            chartElement: pdfChartRef.current,
            advice: pdfChartJob.report.description || '',
            metrics: {
              swing: null,
              volatility: null,
              uncertainty: null,
              bandWidth: null,
            },
            forecastData: pdfChartJob.prediction.forecast || [],
            anomalies: pdfChartJob.anomalies,
            // Scenario metrics are stored under `results` in the DB record;
            // the report builder expects the same shape whatif.tsx computes
            // them in (adjustedTotal, percentChange).
            scenarios: (pdfChartJob.scenarios || []).map((s: any) => ({
              name: s.name,
              metrics: s.results && typeof s.results === 'object' && 'adjustedTotal' in s.results ? s.results : null,
            })),
          });
          success('PDF Generated', 'Report downloaded');
        } catch (e) {
          info('PDF export failed', String(e));
        } finally {
          setPdfGenerating(null);
          setPdfChartJob(null);
        }
      });
      return () => cancelAnimationFrame(raf2);
    });
    return () => cancelAnimationFrame(raf1);
  }, [pdfChartJob]);

  const ReportPreview = ({ report }: any) => (
    <div className="space-y-4">
      <div>
        <h3 className="font-semibold text-lg mb-2">{report.name}</h3>
        <p className="text-sm text-muted-foreground whitespace-pre-wrap">{report.description}</p>
      </div>
      <div className="text-xs text-muted-foreground space-y-1">
        <div>Generated: {new Date(report.created_at).toLocaleDateString()}</div>
        <div>Views: {report.view_count || 0}</div>
      </div>
      <div className="flex flex-wrap gap-2 pt-4 border-t border-border/50">
        <button
          onClick={() => downloadReport(report, 'json')}
          className="px-3 py-2 rounded-lg text-xs font-medium bg-primary/20 text-primary hover:bg-primary/30 transition-colors inline-flex items-center gap-1"
        >
          <FiDownload className="h-3 w-3" /> JSON
        </button>
        <button
          onClick={() => downloadReportCSV(report)}
          className="px-3 py-2 rounded-lg text-xs font-medium bg-primary/20 text-primary hover:bg-primary/30 transition-colors inline-flex items-center gap-1"
        >
          <FiDownload className="h-3 w-3" /> CSV
        </button>
        <button
          onClick={() => downloadReportPDF(report)}
          disabled={pdfGenerating === report.id}
          className="px-3 py-2 rounded-lg text-xs font-medium text-white disabled:opacity-50 transition-colors inline-flex items-center gap-1"
          style={{ background: 'var(--gradient-primary)' }}
        >
          <FiFileText className="h-3 w-3" /> {pdfGenerating === report.id ? 'Building PDF…' : 'PDF'}
        </button>
        <button
          onClick={() => {
            const config = typeof report.config === 'string' ? JSON.parse(report.config) : report.config;
            const predId = config?.predictionIds?.[0];
            if (predId) generateReport(predId);
          }}
          className="flex-1 px-3 py-2 rounded-lg text-xs font-medium bg-accent/20 hover:bg-accent/30 transition-colors inline-flex items-center justify-center gap-1"
        >
          <FiRefreshCw className="h-3 w-3" /> Regenerate
        </button>
        <button
          onClick={() => deleteReport(report.id)}
          className="px-3 py-2 rounded-lg text-xs text-destructive hover:bg-destructive/10 transition-colors"
          title="Delete"
        >
          <FiTrash2 className="h-3 w-3" />
        </button>
      </div>
    </div>
  );

  if (loading) {
    return (
      <div className="space-y-6">
        <div>
          <h1 className="text-2xl font-semibold">Reports</h1>
          <p className="text-sm text-muted-foreground">Auto-generated forecast reports with preview and regeneration.</p>
        </div>
        <SkeletonCardGrid count={6} />
      </div>
    );
  }

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl font-semibold">Reports</h1>
        <p className="text-sm text-muted-foreground">Auto-generated forecast reports with preview and regeneration.</p>
      </div>

      {/* Quick Stats */}
      <div className="grid grid-cols-2 md:grid-cols-4 gap-4">
        <GlassCard>
          <div className="text-xs text-muted-foreground mb-1">Total Reports</div>
          <div className="text-2xl font-semibold">{reports.length}</div>
        </GlassCard>
        <GlassCard>
          <div className="text-xs text-muted-foreground mb-1">Total Forecasts</div>
          <div className="text-2xl font-semibold">{predictions.length}</div>
        </GlassCard>
        <GlassCard>
          <div className="text-xs text-muted-foreground mb-1">With Reports</div>
          <div className="text-2xl font-semibold">
            {predictions.filter((p) => reports.some((r: any) => {
              const config = typeof r.config === 'string' ? JSON.parse(r.config) : r.config;
              return config?.predictionIds?.includes(p.id);
            })).length}
          </div>
        </GlassCard>
        <GlassCard>
          <div className="text-xs text-muted-foreground mb-1">Without Reports</div>
          <div className="text-2xl font-semibold">
            {predictions.filter((p) => !reports.some((r: any) => {
              const config = typeof r.config === 'string' ? JSON.parse(r.config) : r.config;
              return config?.predictionIds?.includes(p.id);
            })).length}
          </div>
        </GlassCard>
      </div>

      {/* Search and Filter */}
      <div className="flex gap-3 flex-wrap">
        <div className="flex-1 min-w-[200px] relative">
          <FiSearch className="absolute left-3 top-1/2 -translate-y-1/2 h-4 w-4 text-muted-foreground" />
          <input
            type="text"
            placeholder="Search forecasts..."
            value={search}
            onChange={(e) => setSearch(e.target.value)}
            className="w-full pl-10 pr-4 py-2 rounded-lg bg-muted/30 border border-border/50 outline-none focus:border-primary/50 transition-colors text-sm"
          />
        </div>
        <select
          value={filter}
          onChange={(e) => setFilter(e.target.value)}
          className="px-3 py-2 rounded-lg bg-muted/30 border border-border/50 outline-none focus:border-primary/50 transition-colors text-sm"
        >
          <option value="all">All Forecasts</option>
          <option value="with-reports">Has Reports</option>
          <option value="without-reports">Needs Reports</option>
        </select>
      </div>

      {/* Reports Grid */}
      {reports.length > 0 && (
        <div>
          <h2 className="text-lg font-semibold mb-4">Available Reports ({reports.length})</h2>
          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
            {reports.map((report) => (
              <GlassCard key={report.id} className="flex flex-col">
                <div
                  className="cursor-pointer flex-1"
                  onClick={() => setPreviewId(report.id)}
                >
                  <h3 className="font-semibold text-sm mb-2 truncate">{report.name}</h3>
                  <p className="text-xs text-muted-foreground line-clamp-2 mb-3">
                    {report.description}
                  </p>
                </div>
                <div className="flex gap-2 pt-3 border-t border-border/50">
                  <button
                    onClick={() => setPreviewId(report.id)}
                    className="flex-1 px-3 py-2 rounded-lg text-xs font-medium bg-primary/20 text-primary hover:bg-primary/30 transition-colors"
                  >
                    Preview
                  </button>
                  <button
                    onClick={() => downloadReportCSV(report)}
                    className="px-3 py-2 rounded-lg text-xs text-muted-foreground hover:text-foreground hover:bg-muted/50 transition-colors"
                    title="Download as CSV"
                  >
                    <FiDownload className="h-3.5 w-3.5" />
                  </button>
                  <button
                    onClick={() => downloadReportPDF(report)}
                    disabled={pdfGenerating === report.id}
                    className="px-3 py-2 rounded-lg text-xs text-primary hover:bg-primary/10 disabled:opacity-50 transition-colors"
                    title="Download professional PDF"
                  >
                    <FiFileText className="h-3.5 w-3.5" />
                  </button>
                  <button
                    onClick={() => {
                      const config = typeof report.config === 'string' ? JSON.parse(report.config) : report.config;
                      const predId = config?.predictionIds?.[0];
                      if (predId) generateReport(predId);
                    }}
                    disabled={generating === report.id}
                    className="px-3 py-2 rounded-lg text-xs text-muted-foreground hover:text-foreground hover:bg-muted/50 disabled:opacity-50 transition-colors"
                    title="Regenerate report"
                  >
                    {generating === report.id ? 'Generating...' : <FiRefreshCw className="h-3.5 w-3.5" />}
                  </button>
                  <button
                    onClick={() => deleteReport(report.id)}
                    className="px-3 py-2 rounded-lg text-xs text-destructive hover:bg-destructive/10 transition-colors"
                    title="Delete report"
                  >
                    <FiTrash2 className="h-3.5 w-3.5" />
                  </button>
                </div>
              </GlassCard>
            ))}
          </div>
        </div>
      )}

      {/* Forecasts Without Reports */}
      {filteredPredictions.filter((p) => !reports.some((r: any) => {
        const config = typeof r.config === 'string' ? JSON.parse(r.config) : r.config;
        return config?.predictionIds?.includes(p.id);
      })).length > 0 && (
        <div>
          <h2 className="text-lg font-semibold mb-4">
            Generate Reports
            <span className="text-sm font-normal text-muted-foreground ml-2">
              ({filteredPredictions.filter((p) => !reports.some((r: any) => {
                const config = typeof r.config === 'string' ? JSON.parse(r.config) : r.config;
                return config?.predictionIds?.includes(p.id);
              })).length} forecasts without reports)
            </span>
          </h2>
          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
            {filteredPredictions
              .filter((p) => !reports.some((r: any) => {
                const config = typeof r.config === 'string' ? JSON.parse(r.config) : r.config;
                return config?.predictionIds?.includes(p.id);
              }))
              .map((prediction) => (
                <GlassCard key={prediction.id} className="flex flex-col">
                  <div className="flex-1">
                    <h3 className="font-semibold text-sm mb-2">{prediction.name}</h3>
                    <div className="text-xs text-muted-foreground space-y-1">
                      <div>{prediction.algorithm} • {prediction.horizon} {prediction.period}</div>
                      <div>Accuracy: {prediction.accuracy || 'N/A'}%</div>
                      <div>Created: {new Date(prediction.createdAt).toLocaleDateString()}</div>
                    </div>
                  </div>
                  <button
                    onClick={() => generateReport(prediction.id)}
                    disabled={generating === prediction.id}
                    className="mt-3 w-full px-4 py-2 rounded-lg text-sm font-medium text-white bg-gradient-primary hover:opacity-90 disabled:opacity-50 transition-all inline-flex items-center justify-center gap-2"
                    style={{ background: 'var(--gradient-primary)' }}
                  >
                    {generating === prediction.id ? (
                      <>Generating...</>
                    ) : (
                      <><FiPlus className="h-4 w-4" /> Generate Report</>
                    )}
                  </button>
                </GlassCard>
              ))}
          </div>
        </div>
      )}

      {/* Preview Modal */}
      {previewId && (
        <div className="fixed inset-0 z-50 grid place-items-center p-4" role="dialog">
          <div className="absolute inset-0 bg-background/70 backdrop-blur-sm" onClick={() => setPreviewId(null)} />
          <div className="relative w-full max-w-2xl bg-background border border-border rounded-2xl shadow-2xl p-6 max-h-[80vh] overflow-y-auto">
            <div className="flex items-center justify-between mb-4 pb-4 border-b border-border">
              <h2 className="text-xl font-semibold">Report Preview</h2>
              <button
                onClick={() => setPreviewId(null)}
                className="rounded-lg h-8 w-8 grid place-items-center text-muted-foreground hover:text-foreground hover:bg-accent/40"
              >
                <FiX className="h-4 w-4" />
              </button>
            </div>
            <ReportPreview report={reports.find((r) => r.id === previewId)} />
          </div>
        </div>
      )}

      {!loading && reports.length === 0 && predictions.length === 0 && (
        <GlassCard className="text-center py-12">
          <p className="text-muted-foreground mb-4">No forecasts or reports yet.</p>
          <p className="text-sm text-muted-foreground">Create a forecast on the Predictions tab to generate reports automatically.</p>
        </GlassCard>
      )}

      {/* Off-screen chart used only to render a PNG for the PDF export.
          Positioned outside the viewport (not display:none — html2canvas
          needs it laid out and painted) and torn down once the PDF is built. */}
      {pdfChartJob && (
        <div
          ref={pdfChartRef}
          style={{ position: "fixed", top: "-9999px", left: "-9999px", width: 900, height: 400, background: "#ffffff", padding: 16 }}
        >
          <ResponsiveContainer width="100%" height="100%">
            <ComposedChart data={pdfChartJob.prediction.forecast || []} margin={{ top: 8, right: 16, bottom: 0, left: 0 }}>
              <CartesianGrid stroke="#e5e7eb" strokeDasharray="3 6" vertical={false} />
              <XAxis dataKey="label" stroke="#6b7280" fontSize={11} />
              <YAxis stroke="#6b7280" fontSize={11} domain={["auto", "auto"]} />
              <Tooltip />
              <Line type="monotone" dataKey="value" name="Forecast" stroke="#7c5cff" strokeWidth={2.5} dot={{ r: 3 }} />
              <Line type="monotone" dataKey="high" name="Upper Bound" stroke="#22c55e" strokeWidth={1.5} strokeDasharray="4 4" dot={false} opacity={0.7} />
              <Line type="monotone" dataKey="low" name="Lower Bound" stroke="#ef4444" strokeWidth={1.5} strokeDasharray="4 4" dot={false} opacity={0.7} />
            </ComposedChart>
          </ResponsiveContainer>
        </div>
      )}
    </div>
  );
}
