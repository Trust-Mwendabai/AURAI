<?php
/**
 * Auto-report generation
 *
 * Automatically generates report summaries when forecasts complete. The
 * numeric section (totals, range, average) is always computed locally, so a
 * report is never wrong even without AI. When Gemini is configured, its
 * narrative (trend analysis, risks, recommended actions) is prepended —
 * turning the same figures into something a business reader can act on
 * without doing the arithmetic themselves.
 *
 * Stores in saved_reports table for viewing with preview and regenerate option.
 */

require_once __DIR__ . '/lib/helpers.php';
require_once __DIR__ . '/lib/gemini.php';

function generateAutoReport($userId, $predictionId) {
  $db = db();

  try {
    $query = "
      SELECT p.id, p.name, p.target, p.algorithm, p.horizon, p.period, p.accuracy, p.forecast,
             p.dataset_id, d.name as dataset_name, d.rows as dataset_rows
      FROM predictions p
      LEFT JOIN datasets d ON p.dataset_id = d.id
      WHERE p.id = :pid AND p.user_id = :uid
    ";
    $stmt = $db->prepare($query);
    $stmt->execute([':pid' => $predictionId, ':uid' => $userId]);
    $prediction = $stmt->fetch();

    if (!$prediction) {
      return null;
    }

    $reportTitle = "{$prediction['target']} Forecast Report";
    $reportSummary = generateReportSummary($prediction);

    $reportId = uuid4();
    $config = json_encode([
      'predictionIds' => [$predictionId],
      'autoGenerated' => true,
      'type' => 'forecast'
    ]);

    $query = "
      INSERT INTO saved_reports (id, user_id, name, description, config, created_at, updated_at)
      VALUES (:id, :uid, :name, :description, :config, NOW(), NOW())
    ";
    $stmt = $db->prepare($query);
    $stmt->execute([
      ':id' => $reportId,
      ':uid' => $userId,
      ':name' => $reportTitle,
      ':description' => $reportSummary,
      ':config' => $config,
    ]);

    return $reportId;
  } catch (Exception $e) {
    error_log("Auto-report generation failed: " . $e->getMessage());
    return null;
  }
}

/**
 * The always-present, purely computed section: totals, average, range. Never
 * depends on AI being configured, so a report is always at least this useful.
 */
function computeForecastFigures($prediction) {
  $forecast = json_decode($prediction['forecast'], true) ?: [];
  $values = array_map(fn($f) => (float)($f['value'] ?? 0), $forecast);
  $lows = array_map(fn($f) => (float)($f['low'] ?? 0), $forecast);
  $highs = array_map(fn($f) => (float)($f['high'] ?? 0), $forecast);

  if (!$values) return null;

  $total = array_sum($values);
  $average = $total / count($values);

  return [
    'forecast' => $forecast,
    'values' => $values,
    'total' => $total,
    'totalLow' => array_sum($lows),
    'totalHigh' => array_sum($highs),
    'average' => $average,
    'avgLow' => $lows ? array_sum($lows) / count($lows) : 0,
    'avgHigh' => $highs ? array_sum($highs) / count($highs) : 0,
    'peakHigh' => $highs ? max($highs) : max($values),
    'troughLow' => $lows ? min($lows) : min($values),
    // How wide the confidence band is, as a share of the estimate — the same
    // "how sure is the model" read used elsewhere in the app.
    'bandWidthPct' => (function () use ($values, $lows, $highs) {
      $widths = [];
      foreach ($values as $i => $v) {
        if ($v == 0 || !isset($lows[$i], $highs[$i])) continue;
        $widths[] = (($highs[$i] - $lows[$i]) / abs($v)) * 100;
      }
      return $widths ? array_sum($widths) / count($widths) : null;
    })(),
  ];
}

/**
 * Last handful of recorded values, so the AI narrative can speak to *why*
 * the forecast looks the way it does rather than only restating it.
 */
function recentHistory($prediction, int $limit = 12): array {
  $rows = json_decode($prediction['dataset_rows'] ?? '[]', true) ?: [];
  $target = $prediction['target'];
  if (!$rows || !$target) return [];

  $headers = array_keys($rows[0]);
  $dateColumn = null;
  foreach ($headers as $h) {
    if ($h === $target) continue;
    $hits = 0;
    foreach (array_slice($rows, 0, 20) as $row) {
      $v = trim((string)($row[$h] ?? ''));
      if ($v !== '' && (preg_match('/^\d{4}$/', $v) || strtotime($v) !== false)) $hits++;
    }
    if ($hits / max(1, min(20, count($rows))) >= 0.6) { $dateColumn = $h; break; }
  }
  if (!$dateColumn) return [];

  $points = [];
  foreach ($rows as $row) {
    if (!is_numeric($row[$target] ?? null)) continue;
    $ts = strtotime((string)($row[$dateColumn] ?? ''));
    if (!$ts) continue;
    $points[] = ['ts' => $ts, 'label' => date('Y-m-d', $ts), 'value' => round((float)$row[$target], 2)];
  }
  usort($points, fn($a, $b) => $a['ts'] <=> $b['ts']);
  return array_slice($points, -$limit);
}

/**
 * Asks Gemini for the narrative half of the report: verdict, trend drivers,
 * risks, and concrete next steps. Returns null (never throws) if Gemini is
 * unavailable or fails, so the caller always has the computed figures to
 * fall back to.
 */
function generateAiNarrative($prediction, array $figures): ?string {
  if (!gemini_available()) return null;

  $history = recentHistory($prediction);
  $historyLines = $history
    ? implode("\n", array_map(fn($p) => "  {$p['label']}: {$p['value']}", $history))
    : '  (no recorded history available)';

  $forecastLines = implode("\n", array_map(
    fn($f) => "  {$f['label']}: estimate " . number_format($f['value'] ?? 0, 1)
      . ", range " . number_format($f['low'] ?? 0, 1) . " - " . number_format($f['high'] ?? 0, 1),
    $figures['forecast']
  ));

  $prompt = "Dataset: {$prediction['dataset_name']}\n"
    . "Target column: {$prediction['target']}\n"
    . "Model: {$prediction['algorithm']} | Horizon: {$prediction['horizon']} {$prediction['period']} | "
    . "Accuracy: " . ($prediction['accuracy'] !== null ? $prediction['accuracy'] . '%' : 'not scored') . "\n\n"
    . "RECENT RECORDED HISTORY (most recent last)\n{$historyLines}\n\n"
    . "FORECAST\n{$forecastLines}\n\n"
    . "Write a report narrative with exactly these four sections, each with a bold heading:\n\n"
    . "**Executive Summary** — Two to three sentences. Is {$prediction['target']} trending up, down, or flat, "
    . "by roughly how much, and what does that mean for the business right now?\n\n"
    . "**Trend Analysis** — What in the recorded history explains the direction the forecast continues? "
    . "Call out momentum, seasonality, or a turning point if one is visible.\n\n"
    . "**Key Risks** — What could make the actual result land outside the forecast range? Be specific to "
    . "this data, not generic hedging.\n\n"
    . "**Recommended Actions** — Exactly three concrete, numbered actions, each tied to a specific figure "
    . "from the forecast above.\n\n"
    . "Write for a business reader making a decision, not a data scientist. No preamble, no restating these "
    . "instructions, no closing summary — end after the third action. Keep the whole thing under 350 words.";

  return gemini_generate(
    gemini_system_prompt(
      'You are Aurai, a forecasting analyst writing an executive report section. You are precise with '
      . 'numbers, direct about uncertainty, and never invent a figure that was not given to you.'
    ),
    $prompt,
    ['maxOutputTokens' => 900, 'temperature' => 0.3]
  );
}

function generateReportSummary($prediction) {
  $figures = computeForecastFigures($prediction);

  if (!$figures) {
    return "Forecast for {$prediction['target']}\n\nNo forecast points were produced for this run.";
  }

  $header = "Forecast for {$prediction['target']}\n\n"
    . "Model: {$prediction['algorithm']} | Horizon: {$prediction['horizon']} {$prediction['period']} | "
    . "Accuracy: " . ($prediction['accuracy'] !== null ? $prediction['accuracy'] . '%' : 'not scored') . "\n\n";

  $figuresBlock = "FORECAST RANGE\n"
    . "• Total: " . number_format($figures['totalLow'], 0) . " - " . number_format($figures['totalHigh'], 0)
    . " (Est: " . number_format($figures['total'], 0) . ")\n"
    . "• Average per period: " . number_format($figures['avgLow'], 1) . " - " . number_format($figures['avgHigh'], 1)
    . " (Est: " . number_format($figures['average'], 1) . ")\n"
    . "• Range: " . number_format($figures['troughLow'], 1) . " (Low) to " . number_format($figures['peakHigh'], 1) . " (High)\n"
    . ($figures['bandWidthPct'] !== null
        ? "• Confidence band: ±" . number_format($figures['bandWidthPct'] / 2, 1) . "% around the estimate\n"
        : '');

  $aiNarrative = generateAiNarrative($prediction, $figures);

  if ($aiNarrative) {
    // AI analysis leads (it's what a reader acts on); the computed figures
    // follow as the evidence, always present regardless of whether the AI
    // call succeeded.
    return $header . trim($aiNarrative) . "\n\n" . $figuresBlock;
  }

  // No AI available — the original template-only report, unchanged.
  return $header . $figuresBlock . "\n"
    . "CONFIDENCE INTERVAL\n"
    . "The forecast shows the best estimate with upper and lower confidence bounds. The actual result is "
    . "likely to fall within this range with statistical confidence.";
}

// Scheduled Refreshes (api/schedules.php) reuses generateAutoReport() above by
// require_once-ing this file directly, outside of index.php's normal routing
// — defining AURAI_LIB_ONLY first so this tail HTTP handler, which would
// otherwise run immediately against whatever request is actually in flight,
// stays inert.
if (!defined('AURAI_LIB_ONLY') && $_SERVER['REQUEST_METHOD'] === 'POST') {
  header('Content-Type: application/json');
  $userId = require_auth();
  $data = json_decode(file_get_contents('php://input'), true);
  $predictionId = $data['prediction_id'] ?? null;

  if (!$predictionId) {
    http_response_code(400);
    echo json_encode(['error' => 'prediction_id required']);
    exit;
  }

  $reportId = generateAutoReport($userId, $predictionId);
  if ($reportId) {
    echo json_encode(['success' => true, 'report_id' => $reportId]);
  } else {
    http_response_code(500);
    echo json_encode(['error' => 'Failed to generate report']);
  }
  exit;
}
